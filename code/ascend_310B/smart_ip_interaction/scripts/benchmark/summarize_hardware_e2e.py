"""Summarize real-hardware end-to-end benchmark logs.

The script reads JSONL logs generated by run_pipeline.py, backend/server.py and
scripts/video_player.py when SMART_IP_BENCH_DIR is set. Optional trial CSV files
provide ground-truth windows for action and expression accuracy.
"""

